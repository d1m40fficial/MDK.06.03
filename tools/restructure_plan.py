def main():
    course = json.loads(P.read_text(encoding="utf-8"))
    old_lek, old_prakt = {}, {}
    for ch in course.get("chapters", []):
        d = ch.get("dir", "")
        m = re.match(r"\d+-lek-(\d+)", d)
        if m:
            old_lek[int(m.group(1))] = ch
        m = re.match(r"\d+-prakt-(\d+)", d)
        if m:
            old_prakt[int(m.group(1))] = ch

    new = []
    for pos, (kind, idx, title) in enumerate(PLAN, 1):
        if kind == "lek":
            src = old_lek.get(idx, {})
            entry = {
                "n": pos, "dir": f"{pos:02d}-lek-{idx:02d}", "slug": f"lek-{idx:02d}",
                "title": f"Лекция {idx}. {title}",
                "summary": src.get("summary", ""),
                "minutes": 90, "level": "СПО", "glyph": f"Л{idx}",
                "outcomes": src.get("outcomes", []),
                "topics": src.get("topics", []),
                "figures": src.get("figures", []),
                "status": src.get("status", "planned"),
            }
        else:
            mins = 180 if idx in DOUBLES else 90
            summary, topics = PRAKT_META[idx]
            entry = {
                "n": pos, "dir": f"{pos:02d}-prakt-{idx:02d}", "slug": f"prakt-{idx:02d}",
                "title": f"Практика {idx}. {title}",
                "summary": summary,
                "minutes": mins, "level": "СПО", "glyph": f"П{idx}",
                "outcomes": [],
                "topics": topics,
                "figures": [],
                "status": "planned",
            }
            if idx == 1 and 1 in old_prakt:  # keep the finished Практика 1
                entry["outcomes"] = old_prakt[1].get("outcomes", [])
                entry["figures"] = old_prakt[1].get("figures", [])
        new.append(entry)

    course["chapters"] = new
    course["level"] = "СПО"
    course["hours"] = 63
    P.write_text(json.dumps(course, ensure_ascii=False, indent=2), encoding="utf-8")

    singles = [c for c in new if "prakt" in c["dir"] and c["minutes"] == 90]
    doubles = [c for c in new if "prakt" in c["dir"] and c["minutes"] == 180]
    print(f"chapters: {len(new)} ({sum('lek' in c['dir'] for c in new)} lectures, "
          f"{len(singles)} single practicals, {len(doubles)} double practicals)")
    slot = 1
    for c in new:
        p = max(1, round(c["minutes"] / 90))
        label = f"{slot}" if p == 1 else f"{slot}-{slot + p - 1}"
        slot += p
    print(f"total lesson slots: {slot - 1}")


if __name__ == "__main__":
    main()
