from docx.shared import Pt

HERE = Path(__file__).parent


def line(doc, text, bold=False, size=12, align=None, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.size = Pt(size)
    if align is not None:
        p.alignment = align
    return p


def slot(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.italic = True
    r.font.size = Pt(10)


def table(doc, title, columns, rows, size=9):
    if title:
        line(doc, title, bold=True)
    t = doc.add_table(rows=1, cols=len(columns))
    t.style = "Table Grid"
    for i, c in enumerate(columns):
        cell = t.rows[0].cells[i]
        cell.text = c
        for p in cell.paragraphs:
            for r in p.runs:
                r.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
    for row in t.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(size)
    doc.add_paragraph()
    return t


def base(number, title, minutes):
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    line(doc, "Управление проектами (МДК.03.02)", bold=True, size=14, align=WD_ALIGN_PARAGRAPH.CENTER)
    line(doc, f"Практическая работа {number}", bold=True, size=13, align=WD_ALIGN_PARAGRAPH.CENTER)
    line(doc, title, align=WD_ALIGN_PARAGRAPH.CENTER)
    line(doc, f"Продолжительность: {minutes} минут", align=WD_ALIGN_PARAGRAPH.CENTER, italic=True)
    doc.add_paragraph()
    line(doc, "ФИО студента: ______________________________________")
    line(doc, "Группа: ______________________  Дата: _______________")
    line(doc, "Проект: ____________________________________________")
    doc.add_paragraph()
    line(doc, "Цель работы", bold=True)
    line(doc, "Собрать и проверить проектный документ так, чтобы его мог понять новый участник команды и комиссия. Все решения должны опираться на числа и проверяемые факты.")
    doc.add_paragraph()
    return doc


def finish(doc, questions, criteria):
    line(doc, "Контрольные вопросы", bold=True)
    for i, q in enumerate(questions, 1):
        line(doc, f"{i}. {q}")
    doc.add_paragraph()
    line(doc, "Критерии оценки", bold=True)
    table(doc, "", ["Балл", "Что должно быть сделано"], criteria)
    line(doc, "Вывод", bold=True)
    line(doc, "________________________________________________________________________")
    line(doc, "________________________________________________________________________")
    line(doc, "________________________________________________________________________")


